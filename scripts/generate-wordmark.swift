#!/usr/bin/env swift
// Export the pinned, openly licensed lettering as native and portable vectors.
import AppKit
import CoreText
import CryptoKit
import Foundation

if CommandLine.arguments.count != 1 {
    print("Usage: swift scripts/generate-wordmark.swift\nRegenerates native and SVG wordmark outlines from the pinned local source font.")
    exit(CommandLine.arguments.dropFirst().elementsEqual(["--help"]) ? 0 : 1)
}

let root = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
let fontURL = root.appendingPathComponent("design-assets/wordmark/vendor/LeckerliOne-Regular.ttf")
let fontData = try Data(contentsOf: fontURL)
let expectedHash = "3f38ed99a07ab426eaa64c7d5773850a5dc8e6719b03125efce2cfbc82b083d7"
let hash = SHA256.hash(data: fontData).map { String(format: "%02x", $0) }.joined()
guard hash == expectedHash, let provider = CGDataProvider(data: fontData as CFData),
    let graphicsFont = CGFont(provider)
else { fatalError("The pinned wordmark font is missing or has changed.") }

let font = CTFontCreateWithGraphicsFont(graphicsFont, 1000, nil, nil)
let text = NSAttributedString(
    string: "Dockey", attributes: [NSAttributedString.Key(kCTFontAttributeName as String): font])
let line = CTLineCreateWithAttributedString(text)
let lettering = CGMutablePath()
for run in CTLineGetGlyphRuns(line) as! [CTRun] {
    let count = CTRunGetGlyphCount(run)
    var glyphs = [CGGlyph](repeating: 0, count: count)
    var positions = [CGPoint](repeating: .zero, count: count)
    CTRunGetGlyphs(run, CFRange(location: 0, length: 0), &glyphs)
    CTRunGetPositions(run, CFRange(location: 0, length: 0), &positions)
    for index in 0..<count {
        guard let glyph = CTFontCreatePathForGlyph(font, glyphs[index], nil) else {
            fatalError("The wordmark contains a missing glyph.")
        }
        lettering.addPath(glyph, transform: CGAffineTransform(translationX: positions[index].x, y: positions[index].y))
    }
}
// A slight additional forward lean gives the round brush lettering a compact, flowing silhouette.
var lean = CGAffineTransform(a: 1, b: 0, c: 0.12, d: 1, tx: 0, ty: 0)
let styledLettering = lettering.copy(using: &lean)!
let bounds = styledLettering.boundingBoxOfPath
var normalization = CGAffineTransform(a: 1, b: 0, c: 0, d: -1, tx: -bounds.minX, ty: bounds.maxY)
let outline = styledLettering.copy(using: &normalization)!
func number(_ value: CGFloat) -> String { String(format: "%.3f", locale: Locale(identifier: "en_US_POSIX"), value) }
func point(_ value: CGPoint) -> String { "CGPoint(x: \(number(value.x)), y: \(number(value.y)))" }
func pair(_ value: CGPoint) -> String { "\(number(value.x)) \(number(value.y))" }
var swiftCommands: [String] = []
var svgCommands: [String] = []
outline.applyWithBlock { pointer in
    let element = pointer.pointee
    switch element.type {
    case .moveToPoint:
        swiftCommands.append("path.move(to: \(point(element.points[0])))")
        svgCommands.append("M\(pair(element.points[0]))")
    case .addLineToPoint:
        swiftCommands.append("path.addLine(to: \(point(element.points[0])))")
        svgCommands.append("L\(pair(element.points[0]))")
    case .addQuadCurveToPoint:
        swiftCommands.append("path.addQuadCurve(to: \(point(element.points[1])), control: \(point(element.points[0])))")
        svgCommands.append("Q\(pair(element.points[0])) \(pair(element.points[1]))")
    case .addCurveToPoint:
        swiftCommands.append("path.addCurve(to: \(point(element.points[2])), control1: \(point(element.points[0])), control2: \(point(element.points[1])))")
        svgCommands.append("C\(pair(element.points[0])) \(pair(element.points[1])) \(pair(element.points[2]))")
    case .closeSubpath:
        swiftCommands.append("path.closeSubpath()")
        svgCommands.append("Z")
    @unknown default: fatalError("Unsupported vector element.")
    }
}
let swift = """
// Vector lettering generated by scripts/generate-wordmark.swift. Do not edit coordinates by hand.
// Leckerli One: Copyright 2011 Gesine Todt; SIL OFL 1.1.
// See design-assets/wordmark/SOURCE.json and Resources/BrandingLicenses/LeckerliOne-OFL.txt.
import SwiftUI

struct DockeyWordmarkShape: Shape {
    static let aspectRatio: CGFloat = \(number(bounds.width)) / \(number(bounds.height))
    private static let outline: Path = {
        var path = Path()
\(swiftCommands.map { "        " + $0 }.joined(separator: "\n"))
        return path
    }()

    func path(in rect: CGRect) -> Path {
        Self.outline.applying(CGAffineTransform(
            a: rect.width / \(number(bounds.width)), b: 0, c: 0,
            d: rect.height / \(number(bounds.height)), tx: rect.minX, ty: rect.minY))
    }
}

"""
let svg = """
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 \(number(bounds.width)) \(number(bounds.height))" role="img" aria-labelledby="title">
  <title id="title">Dockey</title>
  <!-- Leckerli One, SIL OFL 1.1. See wordmark/SOURCE.json and wordmark/vendor/OFL.txt. -->
  <path fill="currentColor" d="\(svgCommands.joined(separator: " "))"/>
</svg>

"""
try swift.write(to: root.appendingPathComponent("Sources/Dockey/Design/DockeyWordmarkShape.swift"), atomically: true, encoding: .utf8)
try svg.write(to: root.appendingPathComponent("design-assets/dockey-wordmark.svg"), atomically: true, encoding: .utf8)
print("Exported Dockey wordmark: \(number(bounds.width)) × \(number(bounds.height)), \(swiftCommands.count) vector elements.")
